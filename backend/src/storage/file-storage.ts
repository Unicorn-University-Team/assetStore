import { DeleteObjectCommand, GetObjectCommand, HeadBucketCommand, S3Client } from '@aws-sdk/client-s3';
import { Upload } from '@aws-sdk/lib-storage';
import type { Readable } from 'node:stream';
import { env } from '../config/env';

const s3 = new S3Client({
  region: env.awsRegion,
  // Checksums only where S3 requires them. With the SDK default (always CRC32) streamed multipart
  // uploads failed on completion; S3 computes its own checksum for every stored object anyway.
  requestChecksumCalculation: 'WHEN_REQUIRED',
});
const Bucket = env.s3Bucket;

// Asset files in the private S3 bucket. Keys are generated by the backend, never taken from the user.
export const FileStorage = {
  // Streams the body to S3 (multipart upload, the file is never held in memory as a whole).
  // Returns the Upload so the caller can abort it, e.g. when the size limit is hit.
  upload(key: string, body: Readable, contentType: string): Upload {
    return new Upload({ client: s3, params: { Bucket, Key: key, Body: body, ContentType: contentType } });
  },

  async download(key: string): Promise<Readable> {
    const object = await s3.send(new GetObjectCommand({ Bucket, Key: key }));
    return object.Body as Readable;
  },

  async remove(key: string): Promise<void> {
    await s3.send(new DeleteObjectCommand({ Bucket, Key: key }));
  },

  // Throws if the bucket does not exist or the credentials have no access to it.
  async check(): Promise<void> {
    await s3.send(new HeadBucketCommand({ Bucket }));
  },
};
